// cubejs is a CoffeeScript-era script that runs as `.call(this)` and breaks
// under Vite's CJS wrapper. This writes an ES-module copy: run after updating cubejs.
import { readFileSync, writeFileSync } from 'node:fs';

const lib = (f) => readFileSync(new URL(`../node_modules/cubejs/lib/${f}`, import.meta.url), 'utf8');
const license = readFileSync(new URL('../node_modules/cubejs/LICENSE', import.meta.url), 'utf8');
const body = [lib('cube.js'), lib('solve.js')]
  .map((src) => src.replaceAll('}).call(this);', '}).call(globalThis);').replace("this.Cube || require('./cube')", 'this.Cube'))
  .join('\n');
writeFileSync(new URL('../src/vendor/cubejs.js', import.meta.url),
  `/* Generated by scripts/vendor-cubejs.mjs from cubejs ${JSON.parse(readFileSync(new URL('../node_modules/cubejs/package.json', import.meta.url))).version}\n${license}*/\n${body}\nexport default globalThis.Cube;\n`);
